"""
Планирование видеосегментов (Video API, вариант A).

Вспомогательные функции, связанные с идентификацией варианта ролика.
"""


def _variant_id(klass: int, settlement: str) -> str:
    """Идентификатор версии сценария (везде один формат):
    № класса + слово «базовый» + название класса."""
    return f"{klass}_базовый_{settlement}"
