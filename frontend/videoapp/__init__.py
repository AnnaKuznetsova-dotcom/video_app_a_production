"""Пакет videoapp — модульная реализация frontend приложения «AI-куратор видео»
(понятное разбиение старого монолита frontend/app.py по зонам ответственности).

Слои (без циклических зависимостей):
    theme.py         — нижний слой: CSS, цвета, подписи признаков, ассеты,
                       константы длительностей сегментов ролика
    settings.py      — конфигурация: BACKEND_URL, пути к data/, каталог проектов
    landing.py       — лендинг: hero / ценности / шаги / проекты
    questionnaire.py — словарь анкеты, рельса прогресса, фрагмент анкеты,
                       форма заявки
    features.py      — вектор признаков, локальная модель (знаковый SHAP
                       по группам, «сравнение с ближайшим конкурентом»)
    shap_views.py    — графики важности/факторного анализа/хронометража
    video_views.py   — кастомный плеер со сбором метрик, таблица сегментов
    flow.py          — главный сценарий main()

Важно: точка входа frontend/app.py остаётся тонкой, но часть UTM-хелперов, валидаторов телефона и вспомогательных функций обязана быть
определена НАПРЯМУЮ в app.py — юнит-тесты обращаются к ним через
module-атрибуты app.* и патчат st модуля app (см. tests/).
"""

import os
import sys

# frontend/ должен быть в sys.path — отсюда подгружаются analytics и, при
# прямом импорте videoapp без запуска app.py (например, из tools/).
_FRONTEND_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _FRONTEND_DIR not in sys.path:
    sys.path.insert(0, _FRONTEND_DIR)
